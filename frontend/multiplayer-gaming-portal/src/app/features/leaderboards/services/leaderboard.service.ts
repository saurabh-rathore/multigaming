@Injectable({
  providedIn: 'root'
})
export class LeaderboardService {
  // private apiUrl = '/api/v1/leaderboards'; // Conceptual

  constructor(/*private http: HttpClient*/) {}

  getLeaderboard(gameId: string, timeframe: Timeframe, limit: number = 100): Observable<Leaderboard | undefined> {
    console.log(`[LeaderboardService] Fetching leaderboard for game ${gameId}, timeframe ${timeframe}, limit ${limit} (mocked)`);
    // const params = new HttpParams().set('timeframe', timeframe).set('limit', limit.toString());
    // return this.http.get<Leaderboard>(`${this.apiUrl}/${gameId}`, { params });

    const key = `${gameId}_${timeframe}`;
    const leaderboard = MOCK_LEADERBOARDS.get(key);

    if (leaderboard) {
      // Simulate limit
      const limitedLeaderboard = { ...leaderboard, entries: leaderboard.entries.slice(0, limit) };
      return of(limitedLeaderboard).pipe(delay(450));
    }
    // Return an empty leaderboard structure if no specific mock found for that combo
    return of({
        leaderboardId: `lb_${gameId}_${timeframe}_empty`, gameId,
        gameName: gameId.replace(/_id$/, '').replace(/_/g, ' '), // simple name generation
        timeframe, entries: [], generatedAt: new Date().toISOString()
    }).pipe(delay(450));
  }
}
