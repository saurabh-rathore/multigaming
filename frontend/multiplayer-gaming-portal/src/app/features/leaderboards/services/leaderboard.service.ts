// Mirroring Leaderboard types from backend conceptual service
export interface LeaderboardEntry {
  userId: string;
  rank: number;
  score: number;
  gamesPlayed: number;
  wins?: number;
  totalWinnings?: number;
  lastPlayedAt?: Date | string;
  displayName?: string;
}

export type Timeframe = 'daily' | 'weekly' | 'monthly' | 'allTime';

export interface Leaderboard {
  leaderboardId: string;
  gameId: string;
  gameName?: string;
  timeframe: Timeframe;
  entries: LeaderboardEntry[];
  generatedAt: Date | string;
}

